#!/usr/bin/env python3
"""Build the test app for a production environment and install it there as a PTE.

Usage: bc-publish-tests-production.py [--force-sync] [--generate-only]

Production cannot run Test or TestRunner codeunits, so the test app is compiled with the PRODUCTION
preprocessor symbol, which makes the test codeunits ordinary codeunits and swaps the test runners for
codeunit "BAASIT Production Test Runner". That runner has to call each test method by name, which AL
cannot do, so this first regenerates codeunit "BAASIT Test Dispatch" from the [Test] procedures.

BC_ENV defaults to Production here. The version in app.json must be higher than the one installed
there, and must not be one a different build (the sandbox one) was ever uploaded under.
"""
import os
import re
import subprocess
import sys

from project_paths import REPO, TOOLS

PROJECT = os.path.join(REPO, "TestSuite", "Test")
CODEUNITS = os.path.join(PROJECT, "Objects", "Codeunits")
DISPATCH = os.path.join(CODEUNITS, "TestDispatch.Codeunit.89973.al")

HEADER = re.compile(r'^codeunit \d+ "([^"]+)"', re.M)
TEST_ATTR = re.compile(r"^    \[Test\]\n", re.M)
TEST_METHOD = re.compile(r"^    \[Test\]\n(?:#endif\n)?(?:    \[[^\n]*\]\n)*    procedure (\w+)\(", re.M)


def test_codeunits():
    for name in sorted(os.listdir(CODEUNITS)):
        source = open(os.path.join(CODEUNITS, name), encoding="utf-8-sig").read()
        if "\n    Subtype = Test;\n" not in source:
            continue
        methods = TEST_METHOD.findall(source)
        if len(methods) != len(TEST_ATTR.findall(source)):
            sys.exit(f"ERROR: {name}: found {len(TEST_ATTR.findall(source))} [Test] attributes but {len(methods)} test procedures")
        yield name.split(".")[0], HEADER.search(source).group(1), methods


def generate():
    units = list(test_codeunits())
    out = ["#if PRODUCTION",
           'codeunit 89973 "BAASIT Test Dispatch"',
           "{",
           "    // Generated by Tools/bc-publish-tests-production.py from the [Test] procedures of the test",
           "    // codeunits, and regenerated on every production publish; do not edit it by hand. AL cannot call",
           '    // a procedure by name, which is what codeunit "BAASIT Production Test Runner" needs this for.',
           "",
           "    procedure TestMethods(CodeunitId: Integer) Methods: List of [Text]",
           "    begin",
           "        case CodeunitId of"]
    for _, codeunit, methods in units:
        out += [f'            Codeunit::"{codeunit}":', "                begin"]
        out += [f"                    Methods.Add('{m}');" for m in methods]
        out += ["                end;"]
    out += ["        end;", "    end;", "",
            "    procedure Run(CodeunitId: Integer; MethodName: Text): Boolean",
            "    begin",
            "        case CodeunitId of"]
    for stem, codeunit, _ in units:
        out += [f'            Codeunit::"{codeunit}":', f"                exit(Run{stem}(MethodName));"]
    out += ["        end;", "        exit(false);", "    end;"]
    for stem, codeunit, methods in units:
        out += ["", f"    local procedure Run{stem}(MethodName: Text): Boolean", "    var",
                f'        Tests: Codeunit "{codeunit}";', "    begin", "        case MethodName of"]
        for m in methods:
            out += [f"            '{m}':", f"                Tests.{m}();"]
        out += ["            else", "                exit(false);", "        end;", "        exit(true);", "    end;"]
    out += ["}", "#endif", ""]
    open(DISPATCH, "w", encoding="utf-8").write("\n".join(out))
    print(f"Generated {os.path.basename(DISPATCH)}: {sum(len(m) for _, _, m in units)} tests in {len(units)} codeunits")


generate()
if "--generate-only" in sys.argv:
    sys.exit(0)
args = [sys.executable, os.path.join(TOOLS, "bc-publish-pte.py"), PROJECT, "--define", "PRODUCTION"]
if "--force-sync" in sys.argv:
    args.append("--force-sync")
sys.exit(subprocess.run(args, env={**os.environ, "BC_ENV": os.environ.get("BC_ENV", "Production")}).returncode)
